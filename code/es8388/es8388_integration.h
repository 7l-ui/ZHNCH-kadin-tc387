#ifndef __ES8388_INTEGRATION_H
#define __ES8388_INTEGRATION_H

#include "../../libraries/zf_common/zf_common_typedef.h"
#include "es8388_unified.h"

// 鸣笛模式定义（与horn_simple兼容）
typedef enum {
    ES8388_HORN_BEEP_1S = 0,
    ES8388_HORN_BEEP_2S,
    ES8388_HORN_BEEP_3S,
    ES8388_HORN_BEEP_2_TIMES,
    ES8388_HORN_BEEP_3_TIMES,
    ES8388_HORN_BEEP_4_TIMES,
    ES8388_HORN_LONG_SHORT,
    ES8388_HORN_RAPID,
    ES8388_HORN_ALARM
} es8388_horn_mode_enum;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     ES8388鸣笛系统初始化
// 返回参数     uint8_t       0:成功，其他:失败
// 使用示例     es8388_horn_init();
// 备注信息     此函数初始化ES8388和I2S接口，应在程序开始时调用一次
//-------------------------------------------------------------------------------------------------------------------
uint8_t es8388_horn_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     ES8388鸣笛控制函数
// 参数说明     mode          鸣笛模式
// 返回参数     void
// 使用示例     es8388_horn_beep(ES8388_HORN_BEEP_1S);
// 备注信息     阻塞式函数，直到鸣笛完成才返回
//-------------------------------------------------------------------------------------------------------------------
void es8388_horn_beep(es8388_horn_mode_enum mode);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     停止当前鸣笛
// 返回参数     void
// 使用示例     es8388_horn_stop();
// 备注信息     紧急停止正在播放的鸣笛声音
//-------------------------------------------------------------------------------------------------------------------
void es8388_horn_stop(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查鸣笛是否正在进行
// 返回参数     uint8_t       1:正在进行，0:空闲
// 使用示例     if(es8388_horn_is_busy()) { ... }
// 备注信息
//-------------------------------------------------------------------------------------------------------------------
uint8_t es8388_horn_is_busy(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置ES8388音量
// 参数说明     volume        音量大小（0~33）
// 参数说明     is_headphone  1:耳机音量，0:喇叭音量
// 返回参数     void
// 使用示例     es8388_set_volume(20, 0); // 设置喇叭音量为20
// 备注信息
//-------------------------------------------------------------------------------------------------------------------
void es8388_set_volume(uint8_t volume, uint8_t is_headphone);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     ES8388鸣笛示例演示
// 返回参数     void
// 使用示例     es8388_horn_demo();
// 备注信息     依次演示所有鸣笛模式，用于测试
//-------------------------------------------------------------------------------------------------------------------
void es8388_horn_demo(void);

#endif /* __ES8388_INTEGRATION_H */