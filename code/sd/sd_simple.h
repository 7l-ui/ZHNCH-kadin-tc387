/*********************************************************************************************************************
* 简化版SD卡控制器实现
* 文件位置：code/sd/sd_simple.h
* 功能：只需配置引脚，一个函数调用即可实现SD卡读写
* 依赖：zf_driver_spi.h（SPI库）
********************************************************************************************************************/

#ifndef _SD_SIMPLE_H_
#define _SD_SIMPLE_H_

#include <stdint.h>

// ==================== SD卡类型定义 ====================
typedef enum {
    SD_TYPE_UNKNOWN = 0,
    SD_TYPE_MMC,
    SD_TYPE_SDV1,
    SD_TYPE_SDV2, 
    SD_TYPE_SDHC,
    SD_TYPE_SDXC
} sd_simple_type_enum;

// ==================== SD卡信息结构体 ====================
typedef struct {
    uint32_t capacity_mb;          // 容量（MB）
    uint32_t block_size;           // 块大小
    uint32_t block_count;          // 块数量
    sd_simple_type_enum type;      // SD卡类型
    uint8_t manufacturer_id;       // 制造商ID
    uint16_t rca;                  // 相对卡地址
} sd_simple_info_struct;

// ==================== SD卡操作函数 ====================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     SD卡初始化
// 返回参数     uint8_t 0-成功，其他-错误代码
// 使用示例     sd_simple_init();
// 备注信息     初始化SD卡和SPI接口，只需调用一次
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取SD卡信息
// 参数说明     *info               SD卡信息结构体指针
// 返回参数     uint8_t 0-成功，其他-错误代码
// 使用示例     sd_simple_info_struct info;
//              sd_simple_get_info(&info);
// 备注信息     如果SD卡未初始化，会自动调用sd_simple_init()
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_get_info(sd_simple_info_struct *info);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读取SD卡数据
// 参数说明     *buffer             数据缓冲区指针
// 参数说明     sector              起始扇区号
// 参数说明     count               扇区数量（每个扇区512字节）
// 返回参数     uint8_t 0-成功，其他-错误代码
// 使用示例     uint8_t buffer[512];
//              sd_simple_read(buffer, 0, 1);
// 备注信息     如果SD卡未初始化，会自动调用sd_simple_init()
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_read(uint8_t *buffer, uint32_t sector, uint32_t count);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     写入SD卡数据
// 参数说明     *buffer             数据缓冲区指针
// 参数说明     sector              起始扇区号
// 参数说明     count               扇区数量（每个扇区512字节）
// 返回参数     uint8_t 0-成功，其他-错误代码
// 使用示例     uint8_t buffer[512];
//              sd_simple_write(buffer, 0, 1);
// 备注信息     如果SD卡未初始化，会自动调用sd_simple_init()
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_write(uint8_t *buffer, uint32_t sector, uint32_t count);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     检查SD卡是否就绪
// 返回参数     uint8_t 1-就绪，0-未就绪
// 使用示例     if(sd_simple_is_ready()) { ... }
// 备注信息     如果SD卡未初始化，会自动尝试初始化
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_is_ready(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取SD卡容量（MB）
// 返回参数     uint32_t SD卡容量（MB），0表示错误
// 使用示例     uint32_t capacity = sd_simple_get_capacity_mb();
// 备注信息     如果SD卡未初始化，会自动调用sd_simple_init()
//-------------------------------------------------------------------------------------------------------------------
uint32_t sd_simple_get_capacity_mb(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     打印SD卡信息到串口
// 使用示例     sd_simple_print_info();
// 备注信息     需要先初始化串口才能看到输出
//-------------------------------------------------------------------------------------------------------------------
void sd_simple_print_info(void);


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     SD卡快速自检（非破坏性）
// 返回参数     uint8_t 0-通过，其他-失败
// 使用示例     if(sd_simple_probe() == 0) { ... }
// 备注信息     只执行初始化和扇区0读取，不会写入SD卡
//-------------------------------------------------------------------------------------------------------------------
uint8_t sd_simple_probe(void);

#endif



